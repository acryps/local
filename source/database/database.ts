import { DatabaseContext, DbClient, DbSet, Entity, ForeignReference, PrimaryReference, QueryProxy, Queryable, RunContext, View, ViewSet } from 'vlquery';
import { DatabaseConnection } from '../types/database-connection';

/**
 * Suffix of entity classes that are kept internal
 */
const pointerSuffix = '_Pointer';

/**
 * Methods exposed on a set, everything else (like the context) stays hidden
 */
const setMethods = [
	'find',
	'toQuery',
	'where',
	'first',
	'single',
	'toArray',
	'count',
	'include',
	'includeTree',
	'orderByAscending',
	'orderByDescending',
	'skip',
	'limit',
	'page'
] as const;

/**
 * Constructor of a context generated by `vlquery create-context`
 */
export type DatabaseContextConstructor<TContext extends DatabaseContext> = new (client: DbClient, runContext?: RunContext) => TContext;

/**
 * Names of the sets which are not pointers
 *
 * the generator names sets after their tables, just like their entity classes, so they share the '_Pointer' suffix
 */
export type ExposedSetName<TContext> = {
	[Key in keyof TContext]: Key extends `${string}${typeof pointerSuffix}` ? never : TContext[Key] extends DbSet<any, any> ? Key : never
}[keyof TContext] & string;

/**
 * Set reduced to its public methods
 */
export type ExposedSet<TSet> = Pick<TSet, typeof setMethods[number] & keyof TSet>;

export type ExposedSets<TContext> = { readonly [Name in ExposedSetName<TContext>]: ExposedSet<TContext[Name]> };
export type ExposedViews<TContext> = TContext extends { views: infer TViews } ? { readonly [Name in keyof TViews]: ExposedSet<TViews[Name]> } : {};

/**
 * Model of a set, distributes over unions of sets
 */
export type ModelOf<TSet> = TSet extends DbSet<infer TModel, any> ? TModel : never;

/**
 * Entities of the sets which are not pointers
 */
export type ExposedModel<TContext> = ModelOf<TContext[ExposedSetName<TContext>]>;

/**
 * Database that hides its context and pointer entities
 */
export abstract class Database<TContext extends DatabaseContext> {
	/**
	 * Unique identifier used to reference across multiple databases
	 */
	readonly tag: string;

	readonly sets: ExposedSets<TContext>;
	readonly views: ExposedViews<TContext>;

	protected readonly client: DbClient;
	protected readonly context: TContext;

	constructor(
		connection: DatabaseConnection,
		contextConstructor: DatabaseContextConstructor<TContext>,
		runContext?: RunContext
	) {
		this.tag = connection.tag;

		this.client = new DbClient({
			host: connection.host,
			database: connection.database,
			user: connection.user,
			password: connection.password
		});

		this.context = new contextConstructor(this.client, runContext);

		const sets: Record<string, object> = {};

		for (let name in this.context) {
			const set = this.context[name];

			if (set instanceof DbSet && !this.isPointer(set.modelConstructor)) {
				sets[name] = this.exposeSet(set);
			}
		}

		this.sets = Object.freeze(sets) as ExposedSets<TContext>;

		const views: Record<string, object> = {};
		const contextViews = (this.context as { views?: Record<string, ViewSet<any, any>> }).views ?? {};

		for (let name in contextViews) {
			views[name] = this.exposeSet(contextViews[name]);
		}

		this.views = Object.freeze(views) as ExposedViews<TContext>;
	}

	/**
	 * Connects to the database, queries issued before are stalled until connected
	 */
	connect() {
		return this.client.connect();
	}

	create<TModel extends ExposedModel<TContext>>(item: TModel, comment?: string): Promise<TModel> {
		this.requireExposed(item.constructor);

		return this.context.create(item, comment);
	}

	update<TModel extends ExposedModel<TContext>>(item: TModel, comment?: string): Promise<TModel> {
		this.requireExposed(item.constructor);

		return this.context.update(item, comment);
	}

	delete<TModel extends ExposedModel<TContext>>(item: TModel, comment?: string): Promise<void> {
		this.requireExposed(item.constructor);

		return this.context.delete(item, comment);
	}

	createDuplicate<TModel extends ExposedModel<TContext>>(item: TModel): TModel {
		this.requireExposed(item.constructor);

		return this.context.createDuplicate(item);
	}

	/**
	 * Loads the referenced entity, returns the prefetched entity if it has been included
	 */
	fetch<TModel extends ExposedModel<TContext>>(reference: Partial<ForeignReference<TModel>>): Promise<TModel> {
		this.requireExposed(reference.$relation);

		return this.context.fetch(reference);
	}

	/**
	 * Query of all entities referencing the item
	 */
	related<TModel extends ExposedModel<TContext> & Entity<TQueryProxy>, TQueryProxy extends QueryProxy>(reference: PrimaryReference<TModel, TQueryProxy>): Queryable<TModel, TQueryProxy> {
		this.requireExposed(reference.$relation);

		return this.context.related(reference);
	}

	/**
	 * Loads missing referenced data defined in the tree
	 */
	backload(item: ExposedModel<TContext>, tree: any): Promise<void> {
		this.requireExposed(item.constructor);

		for (let property in tree) {
			const reference = item[property as keyof typeof item];

			if (reference instanceof ForeignReference || reference instanceof PrimaryReference) {
				this.requireExposed(reference.$relation);
			}
		}

		return this.context.backload(item, tree);
	}

	private exposeSet(set: DbSet<any, any> | ViewSet<any, any>) {
		const exposed: Record<string, Function> = {};

		// bind instead of exposing the set itself, so the context can not be reached through it
		for (let method of setMethods) {
			exposed[method] = set[method].bind(set);
		}

		return Object.freeze(exposed);
	}

	private isPointer(type: Function) {
		return type.name.endsWith(pointerSuffix);
	}

	private requireExposed(type: Function | undefined) {
		if (type && this.isPointer(type)) {
			throw new Error(`'${type.name}' is not exposed by database '${this.tag}'`);
		}
	}
}
