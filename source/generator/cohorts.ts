import { pointerTargetColumn } from '../structure';
import { ForeignKey, Schema, Table } from './schema';

/**
 * Suffix of pointer tables, `account__pointer` is the pointer table of `account`
 */
export const pointerSuffix = '__pointer';

/**
 * Database structure which can not be parsed into cohorts
 */
export class CohortStructureError extends Error {
	constructor(readonly problems: string[]) {
		super(`Invalid cohort structure:\n${problems.map(problem => `- ${problem}`).join('\n')}`);
	}
}

export type Cohort = {
	root: Table;
	pointer: Table;

	/**
	 * Tables of the cohort below the root, every table after the tables of the cohort it references
	 */
	members: CohortMember[];
};

export type CohortMember = {
	table: Table;

	/**
	 * Foreign keys to tables of the cohort, root or members
	 */
	parents: ForeignKey[];
};

/**
 * Schema parsed into cohorts
 */
export type Cohorts = {
	cohorts: Cohort[];

	/**
	 * Cohort of each table which is part of one, by the name of the table
	 */
	cohortOf: Map<string, Cohort>;

	/**
	 * Pointer tables, by their name
	 */
	pointers: Map<string, Cohort>;

	/**
	 * Foreign keys to pointer tables, except the ones of the root ids to their own pointers
	 */
	pointerReferences: ForeignKey[];
};

/**
 * Parses the tables of the schema into cohorts
 *
 * the structure is validated along, every problem found is collected before throwing a CohortStructureError
 * - a pointer table points to a table, consists of a generated id and a text target, references no other tables and is referenced by the id of the table it points to
 * - a table belongs to one cohort at most, as its rows are stored in one database
 * - a table of a cohort has an id of type uuid, as its rows are created in and moved between databases
 * - a top level table references the tables of other cohorts through their pointer tables
 */
export const parseCohorts = (schema: Schema): Cohorts => {
	const problems: string[] = [];
	const tables = new Map(schema.tables.map(table => [table.name, table]));

	const cohorts: Cohort[] = [];
	const pointers = new Map<string, Cohort>();

	for (let pointer of schema.tables) {
		if (!pointer.name.endsWith(pointerSuffix)) {
			continue;
		}

		const root = tables.get(pointer.name.substring(0, pointer.name.length - pointerSuffix.length));

		if (!root) {
			problems.push(`Pointer table '${pointer.name}' does not point to a table, no table '${pointer.name.substring(0, pointer.name.length - pointerSuffix.length)}' found`);

			continue;
		}

		const id = pointer.columns.find(column => column.name == 'id');
		const target = pointer.columns.find(column => column.name == pointerTargetColumn);

		if (!id) {
			problems.push(`Pointer table '${pointer.name}' has no column 'id'`);
		} else if (!id.hasDefault) {
			problems.push(`Pointer table '${pointer.name}' has no default for its id, pointer ids are generated by the database a cohort is created in`);
		}

		if (!target) {
			problems.push(`Pointer table '${pointer.name}' has no column '${pointerTargetColumn}'`);
		} else if (target.type != 'text') {
			problems.push(`Pointer table '${pointer.name}' has a column '${pointerTargetColumn}' of type '${target.type}', the tag of a database is stored as 'text'`);
		}

		for (let column of pointer.columns) {
			if (column != id && column != target) {
				problems.push(`Pointer table '${pointer.name}' has a column '${column.name}', pointer tables only consist of 'id' and '${pointerTargetColumn}'`);
			}
		}

		for (let key of pointer.foreignKeys) {
			problems.push(`Pointer table '${pointer.name}' references '${key.foreignTable}' (column '${key.column}'), pointer tables are stored in every database and can not reference other tables`);
		}

		const rootId = root.columns.find(column => column.name == 'id');

		if (id && id.type != rootId?.type) {
			problems.push(`Pointer table '${pointer.name}' has an id of type '${id.type}', but '${root.name}' has an id of type '${rootId?.type}'`);
		}

		if (!root.foreignKeys.some(key => isRootKey(key, pointer.name))) {
			problems.push(`Table '${root.name}' has a pointer table, but its id does not reference '${pointer.name}' (id). Add 'REFERENCES ${pointer.name} (id)' to its id`);
		}

		const cohort: Cohort = { root, pointer, members: [] };

		cohorts.push(cohort);
		pointers.set(pointer.name, cohort);
	}

	// a foreign key to a pointer table leads into another cohort, it does not join the cohort of the table
	const directKeys = (table: Table) => table.foreignKeys.filter(key => !pointers.has(key.foreignTable) && tables.has(key.foreignTable));
	const rootOf = new Map(cohorts.map(cohort => [cohort.root.name, cohort]));

	/**
	 * Cohorts the table references, directly or through other tables
	 */
	const findCohorts = (table: Table, visited: Set<string>): Set<Cohort> => {
		const root = rootOf.get(table.name);

		if (root) {
			return new Set([root]);
		}

		const found = new Set<Cohort>();

		if (!visited.has(table.name)) {
			visited.add(table.name);

			for (let key of directKeys(table)) {
				for (let cohort of findCohorts(tables.get(key.foreignTable)!, visited)) {
					found.add(cohort);
				}
			}
		}

		return found;
	};

	const cohortOf = new Map<string, Cohort>();

	for (let table of schema.tables) {
		if (pointers.has(table.name)) {
			continue;
		}

		const found = [...findCohorts(table, new Set())];

		if (!found.length) {
			continue;
		}

		// ids are generated in every database and rows are moved between them, sequences would collide
		const id = table.columns.find(column => column.name == 'id');

		if (id?.type != 'uuid') {
			problems.push(`Table '${table.name}' belongs to the cohort of '${found[0].root.name}' but has an id of type '${id?.type}', cohort tables require ids of type 'uuid' to be unique across all databases`);
		}

		if (found.length > 1) {
			problems.push(`Table '${table.name}' belongs to multiple cohorts (${found.map(cohort => `'${cohort.root.name}'`).join(', ')}), its rows can only be stored in one database. Reference all but one of them through their pointer tables`);

			continue;
		}

		const [cohort] = found;
		cohortOf.set(table.name, cohort);

		// tables below the root join the cohorts they reference, which is covered above
		if (cohort.root == table) {
			for (let key of directKeys(table)) {
				const referenced = [...findCohorts(tables.get(key.foreignTable)!, new Set())];

				if (referenced.length && !referenced.includes(cohort)) {
					problems.push(`Top level table '${table.name}' references '${key.foreignTable}' of the cohort of '${referenced[0].root.name}' directly (column '${key.column}'), its rows can be stored in another database. Reference '${referenced[0].root.name}' through its pointer table instead`);
				}
			}
		}
	}

	for (let cohort of cohorts) {
		cohort.members = orderMembers(cohort, schema.tables.filter(table => table != cohort.root && cohortOf.get(table.name) == cohort), directKeys);
	}

	const pointerReferences = schema.tables
		.filter(table => !pointers.has(table.name))
		.flatMap(table => table.foreignKeys.filter(key => pointers.has(key.foreignTable) && !isRootKey(key, key.foreignTable)));

	if (problems.length) {
		throw new CohortStructureError(problems);
	}

	return { cohorts, cohortOf, pointers, pointerReferences };
};

/**
 * Foreign key of the id of a root to its own pointer
 */
export const isRootKey = (key: ForeignKey, pointer: string) => key.column == 'id' && key.foreignTable == pointer && key.table + pointerSuffix == pointer;

/**
 * Orders the members after the tables of the cohort they reference
 *
 * tables referencing each other in a circle are appended in the order of the schema
 */
const orderMembers = (cohort: Cohort, tables: Table[], directKeys: (table: Table) => ForeignKey[]): CohortMember[] => {
	const ordered = new Set<string>([cohort.root.name]);
	const members: CohortMember[] = [];

	const parents = (table: Table) => directKeys(table).filter(key => key.foreignTable == cohort.root.name || tables.some(member => member.name == key.foreignTable));

	let remaining = tables;

	while (remaining.length) {
		const ready = remaining.filter(table => parents(table).every(key => ordered.has(key.foreignTable) || key.foreignTable == table.name));
		const next = ready.length ? ready : [remaining[0]];

		for (let table of next) {
			ordered.add(table.name);
			members.push({ table, parents: parents(table) });
		}

		remaining = remaining.filter(table => !next.includes(table));
	}

	return members;
};
